export const DEFAULT_AGENT_HEARTBEAT = `# 心跳

你现在被周期唤醒，做一次**记忆维护**。目标是让记忆保持最新、可检索、不臃肿。

## 做什么

1. 用 \`memory_search\` 看看最近有没有值得留下的内容（会话要点、用户偏好、已做的决定）。
2. 把要点写进**当天的主题笔记**：\`memory_note(topic, content)\`。
   同一话题重复写是**覆盖**而不是追加，所以可以放心重复跑。
3. 只有**长期稳定**的偏好或事实，才用 \`memory_core\` 追加进核心记忆（默认不要写 —— 核心记忆要短）。
4. 需要更多上下文时，用 \`memory_read\` 按路径展开，**不要凭空猜**。

## 不要做什么

- 不要把整段对话原文抄进记忆，只留要点。
- 不要删除已有记忆。
- 没有值得记的就什么都不做，直接说明「本轮无新增」。

## 想让心跳做别的事

直接改这个文件：心跳每次都会重新读它，改完下一次触发就生效。
`;
